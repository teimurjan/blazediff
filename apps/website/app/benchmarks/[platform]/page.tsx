import {
	PLATFORMS,
	platformLabel,
} from "../../../components/benchmarks/artifacts";
import BenchmarksView from "../../../components/benchmarks/benchmarks-view";

type Props = { params: Promise<{ platform: string }> };

export const dynamicParams = false;

// The first platform is served by /benchmarks itself.
export function generateStaticParams() {
	return PLATFORMS.slice(1).map((platform) => ({ platform }));
}

export async function generateMetadata({ params }: Props) {
	const { platform } = await params;
	return {
		title: `Benchmarks on ${platformLabel(platform)}`,
		description: `BlazeDiff benchmark results measured on ${platformLabel(platform)}. Every number is generated by pnpm benchmark and committed as JSON.`,
	};
}

export default async function PlatformBenchmarksPage({ params }: Props) {
	const { platform } = await params;
	return <BenchmarksView platform={platform} />;
}
